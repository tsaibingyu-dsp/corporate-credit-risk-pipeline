from typing import Literal

from pydantic import Field, StrictBool, StrictFloat, StrictInt
from judicial.schema import StrictModel
from credit_risk.assessment import RiskAssessment, RiskLevel, ASSESSMENT_PROMPT
from company_names import NAME_MATCH_PROMPT


class EnvironmentFinancialImpact(StrictModel):
    amount: StrictInt | StrictFloat | None = Field(ge=0, allow_inf_nan=False)
    currency: str | None
    type: Literal['administrative_fine']
    payment_status: Literal['unknown','paid','unpaid','installments']


class EnvironmentSourceDetails(StrictModel):
    case: str | None
    appeal: str | None
    appeal_result: str | None
    restricted_date_raw: str | None
    improvement_status_raw: str | None
    download_details: dict[str,str] | None = None


class EnvironmentDecision(StrictModel):
    """Only these judgment fields may be generated by Gemini."""
    risk_assessment: RiskAssessment
    company_match: Literal['confirmed', 'possible', 'unrelated']
    event_summary: str | None
    risk_category: list[Literal['compliance', 'operational', 'financial', 'contingent_liability', 'governance', 'environmental', 'credit']]
    severity: RiskLevel
    event_status: Literal['ongoing', 'resolved', 'disputed', 'confirmed', 'unknown']
    risk_reasoning: str | None
    evidence_text: list[str]
    review_required: StrictBool
    limitations: list[str]


class EnvironmentAnalysis(EnvironmentDecision):
    """Final report: Python-owned source facts plus validated AI judgments."""
    source_type: Literal['environment_penalty']
    source_id: str
    company_name: str
    event_date: str | None
    financial_impact: EnvironmentFinancialImpact
    source_url: str | None
    source_details: EnvironmentSourceDetails


